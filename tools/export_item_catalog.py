"""Copy the decoded original 42 item descriptions into the offline runtime."""
import json
from pathlib import Path
root=Path(__file__).resolve().parents[1]
catalog=json.loads((root/'research/original-item-catalog.json').read_text('utf8'))
assert [item['id'] for item in catalog['items']]==list(range(42))
body=json.dumps(catalog['items'],ensure_ascii=False,indent=2)
(root/'app/src/item-catalog.mjs').write_text('// Generated by tools/export_item_catalog.py; original descriptions, not implementation claims.\nexport const ORIGINAL_ITEMS = '+body+';\n','utf8')
